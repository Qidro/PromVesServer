using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Text;

namespace PromVesServer.Service
{
    // Возможные состояния процесса динамического взвешивания.
    // Waiting  - ожидаем появления вагона на платформе.
    // Weighing - обнаружено увеличение нагрузки, считаем, что вагон начал заезжать на платформу.
    public enum WeighingStatus
    {
        Waiting,
        Weighing
    }
    // Результат одного прохода вагона через весовую платформу.
    // ВАЖНО:
    // PeakWeight здесь является максимальной нагрузкой,
    // зарегистрированной за время прохода, за вычетом
    // исходной нагрузки платформы.
    
    // Это пока не гарантированная фактическая масса вагона.
    public class DynamicWeightResult
    {
        public int PortId { get; set; }

        // Максимальная зарегистрированная нагрузка относительно фона.
        public decimal PeakWeight { get; set; }

        // Исходная нагрузка платформы перед появлением вагона.
        public decimal InitialWeight { get; set; }

        // Время начала взвешивания.
        public DateTime StartTime { get; set; }

        // Время завершения взвешивания.
        public DateTime EndTime { get; set; }

        // Продолжительность прохождения вагона.
        public TimeSpan Duration => EndTime - StartTime;
    }

    //Сервис обработки измерений с весовых платформ.
    // Получает каждое измерение с COM-порта,
    // определяет начало и окончание прохода вагона,
    // сохраняет максимальную нагрузку и формирует результат.
    //
    // Для каждого COM-порта создаётся собственное состояние.
    public class DynamicWeightCalculator
    {
        // -------------------------------------------------
        // 1. СИНХРОНИЗАЦИЯ
        // -------------------------------------------------
        // Защищает словарь _ports от одновременного доступа из нескольких потоков.
        // Например:
        // один поток добавляет измерение,
        // другой поток запрашивает состояние порта.
        private readonly object _lock = new();

        // Состояния всех весовых платформ.
        //
        // Ключ   - Id COM-порта.
        // Значение - индивидуальное состояние взвешивания.
        // Например:
        // 1 -> состояние COM1
        // 2 -> состояние COM2
        private readonly Dictionary<int, PortState> _ports = new();


        // -------------------------------------------------
        // 2. НАСТРОЙКИ АЛГОРИТМА
        // -------------------------------------------------
        // Минимальное увеличение нагрузки относительно фона,
        // необходимое для обнаружения вагона.
        // Например:
        // Фоновая нагрузка = 100 кг.
        // Текущая нагрузка = 350 кг.
        // Разница = 250 кг.

        // Если порог равен n кг, начинаем взвешивание.
        private readonly decimal _startThreshold;
        // Порог окончания взвешивания.
        // Если нагрузка относительно исходной нагрузки
        // опустилась до этого значения или ниже,
        ///начинаем отсчитывать время подтверждения окончания.
        // </summary>
        private readonly decimal _endThreshold;

        /// <summary>
        /// Сколько времени нагрузка должна оставаться
        /// ниже порога окончания, прежде чем завершим взвешивание.
        ///
        /// Это защищает от случайного кратковременного
        /// падения показаний.
        /// </summary>
        private readonly TimeSpan _endDelay;

        /// <summary>
        /// Минимальное время, в течение которого
        /// должен продолжаться процесс взвешивания.
        ///
        /// Защищает от ложного срабатывания на короткий скачок.
        /// </summary>
        private readonly TimeSpan _minWeighingTime;

        /// <summary>
        /// Коэффициент обновления фоновой нагрузки.
        ///
        /// Чем меньше значение, тем медленнее меняется фон.
        ///
        /// Используется только в состоянии Waiting.
        /// </summary>
        private readonly decimal _baselineAlpha;


        // -------------------------------------------------
        // 3. СОБЫТИЕ ЗАВЕРШЕНИЯ ВЗВЕШИВАНИЯ
        // -------------------------------------------------

        /// <summary>
        /// Событие вызывается после завершения прохода вагона.
        ///
        /// Подписчик получает объект DynamicWeightResult.
        /// </summary>
        public event Action<DynamicWeightResult>? WeighingCompleted;


        // -------------------------------------------------
        // 4. КОНСТРУКТОР
        // -------------------------------------------------

        public DynamicWeightCalculator(
            decimal startThreshold = 2500m,
            decimal endThreshold = 1000m,
            int endDelayMs = 300,
            int minWeighingTimeMs = 300,
            decimal baselineAlpha = 0.01m)
        {
            _startThreshold = startThreshold;

            _endThreshold = endThreshold;

            _endDelay = TimeSpan.FromMilliseconds(endDelayMs);

            _minWeighingTime =
                TimeSpan.FromMilliseconds(minWeighingTimeMs);

            _baselineAlpha = baselineAlpha;
        }


        // -------------------------------------------------
        // 5. ОСНОВНОЙ МЕТОД
        // -------------------------------------------------

        /// Получает новое измерение с конкретного COM-порта.
        ///
        /// Вызывается после получения и проверки каждого пакета.
        ///
        /// При частоте 150 пакетов в секунду
        /// этот метод будет вызываться примерно 150 раз в секунду.
        public void AddMeasurement(int portId, decimal weight)
        {
            // Здесь будем хранить результат, если
            // в процессе обработки обнаружится окончание взвешивания.
            //
            // Пока мы находимся внутри lock, событие не вызываем.
            DynamicWeightResult? completedResult = null;

            lock (_lock)
            {
                // -----------------------------------------
                // ШАГ 1. Получаем состояние нужного COM-порта
                // -----------------------------------------

                // Если состояние этого порта уже существует,
                // получаем его.
                //
                // Если нет - создаём новое.
                if (!_ports.TryGetValue(portId, out var state))
                {
                    state = new PortState();

                    _ports[portId] = state;
                }


                // -----------------------------------------
                // ШАГ 2. Получаем точное время измерения
                // -----------------------------------------

                // Stopwatch предназначен для измерения интервалов времени.
                //
                // В отличие от DateTime.Now, он не зависит
                // от изменения системных часов.
                long now = Stopwatch.GetTimestamp();


                // -----------------------------------------
                // ШАГ 3. Обрабатываем первое измерение
                // -----------------------------------------

                // При первом получении данных мы ещё не знаем,
                // какая нагрузка является нормальной для платформы.
                //
                // Поэтому принимаем первое измерение
                // за начальную фоновую нагрузку.
                if (!state.Initialized)
                {
                    state.Initialized = true;

                    state.Baseline = weight;

                    state.FilteredWeight = weight;

                    state.LastTimestamp = now;

                    return;
                }


                // -----------------------------------------
                // ШАГ 4. Сглаживаем входящее измерение
                // -----------------------------------------

                // Используем экспоненциальное сглаживание.
                //
                // Формула:
                //
                // Новый результат =
                // Старый результат +
                // Коэффициент * (Новое измерение - Старый результат)
                //
                // Коэффициент 0.25 означает, что мы учитываем
                // 25% отклонения нового значения от предыдущего.
                //
                // Это уменьшает влияние небольших колебаний.
                state.FilteredWeight +=
                    0.25m * (weight - state.FilteredWeight);

                decimal currentWeight = state.FilteredWeight;


                // -----------------------------------------
                // ШАГ 5. Проверяем текущее состояние
                // -----------------------------------------

                if (state.Status == WeighingStatus.Waiting)
                {
                    // =====================================
                    // СОСТОЯНИЕ WAITING
                    // =====================================

                    // В этом состоянии вагон ещё не обнаружен.
                    //
                    // Обновляем фоновую нагрузку платформы.
                    //
                    // Например:
                    // Baseline = 100 кг.
                    // CurrentWeight = 110 кг.
                    //
                    // Постепенно фоновое значение приблизится
                    // к текущему измерению.

                    state.Baseline +=
                        _baselineAlpha *
                        (currentWeight - state.Baseline);


                    // Определяем, насколько текущая нагрузка
                    // отличается от фоновой.
                    decimal difference =
                        currentWeight - state.Baseline;


                    // Если нагрузка выросла достаточно сильно,
                    // считаем, что начался заезд вагона.
                    if (difference >= _startThreshold)
                    {
                        // Меняем состояние.
                        state.Status = WeighingStatus.Weighing;

                        // Запоминаем время начала взвешивания.
                        state.StartTime = now;

                        // Запоминаем исходную нагрузку платформы.
                        state.StartWeight = state.Baseline;

                        // Первое значение максимальной нагрузки.
                        state.PeakWeight = currentWeight;

                        // Сбрасываем таймер окончания.
                        state.BelowThresholdSince = 0;
                    }
                }
                else
                {
                    // =====================================
                    // СОСТОЯНИЕ WEIGHING
                    // =====================================

                    // Вагон уже обнаружен.
                    //
                    // Теперь следим за изменением нагрузки.


                    // -------------------------------------
                    // ШАГ 6. Ищем максимальную нагрузку
                    // -------------------------------------

                    // Если текущее измерение больше предыдущего
                    // максимума, сохраняем новое значение.
                    if (currentWeight > state.PeakWeight)
                    {
                        state.PeakWeight = currentWeight;
                    }


                    // -------------------------------------
                    // ШАГ 7. Проверяем окончание взвешивания
                    // -------------------------------------

                    // Вычисляем разницу между текущей нагрузкой
                    // и исходной нагрузкой платформы.
                    decimal difference =
                        currentWeight - state.StartWeight;


                    // Если нагрузка вернулась почти к исходной,
                    // предполагаем, что вагон покинул платформу.
                    if (difference <= _endThreshold)
                    {
                        // Если это первое измерение ниже порога,
                        // запоминаем время его появления.
                        if (state.BelowThresholdSince == 0)
                        {
                            state.BelowThresholdSince = now;
                        }

                        // Сколько времени нагрузка находится
                        // ниже порога окончания.
                        TimeSpan belowDuration =
                            Stopwatch.GetElapsedTime(
                                state.BelowThresholdSince);


                        // Сколько времени длится всё взвешивание.
                        TimeSpan weighingDuration =
                            Stopwatch.GetElapsedTime(
                                state.StartTime);


                        // Завершаем взвешивание только тогда,
                        // когда оба временных условия выполнены.
                        if (belowDuration >= _endDelay &&
                            weighingDuration >= _minWeighingTime)
                        {
                            // ---------------------------------
                            // ШАГ 8. Формируем результат
                            // ---------------------------------

                            completedResult = new DynamicWeightResult
                            {
                                PortId = portId,

                                // Максимальная нагрузка
                                // минус исходная нагрузка платформы.
                                PeakWeight = Math.Max(
                                    0,
                                    state.PeakWeight - state.StartWeight),

                                InitialWeight = state.StartWeight,

                                // Переводим монотонную временную метку
                                // в DateTime относительно UTC.
                                StartTime = DateTime.UtcNow -
                                    weighingDuration,

                                EndTime = DateTime.UtcNow
                            };


                            // ---------------------------------
                            // ШАГ 9. Сбрасываем состояние
                            // ---------------------------------

                            // Теперь снова ожидаем следующий вагон.
                            state.Status = WeighingStatus.Waiting;

                            state.BelowThresholdSince = 0;

                            state.PeakWeight = 0;
                        }
                    }
                    else
                    {
                        // Если нагрузка снова увеличилась,
                        // значит, условие окончания больше не выполняется.
                        //
                        // Сбрасываем таймер.
                        state.BelowThresholdSince = 0;
                    }
                }

                // Сохраняем время последнего измерения.
                state.LastTimestamp = now;
            }


            // ---------------------------------------------
            // ШАГ 10. Вызываем событие завершения
            // ---------------------------------------------

            // ВАЖНО:
            // Событие вызывается ПОСЛЕ выхода из lock.
            //
            // Это позволяет избежать ситуации, когда
            // обработчик события выполняет долгую операцию,
            // удерживая блокировку всего калькулятора.
            if (completedResult != null)
            {
                WeighingCompleted?.Invoke(completedResult);
            }
        }


        // -------------------------------------------------
        // 6. ВНУТРЕННИЙ КЛАСС СОСТОЯНИЯ ПОРТА
        // -------------------------------------------------

        /// <summary>
        /// Хранит временные данные обработки одного COM-порта.
        ///
        /// Для каждого порта создаётся собственный объект.
        /// </summary>
        private class PortState
        {
            // Показывает, получено ли хотя бы одно измерение.
            public bool Initialized { get; set; }

            // Текущее состояние взвешивания.
            public WeighingStatus Status { get; set; }
                = WeighingStatus.Waiting;

            // Фоновая нагрузка платформы.
            public decimal Baseline { get; set; }

            // Сглаженное текущее значение.
            public decimal FilteredWeight { get; set; }

            // Нагрузка платформы в момент обнаружения вагона.
            public decimal StartWeight { get; set; }

            // Максимальная нагрузка за текущий проход.
            public decimal PeakWeight { get; set; }

            // Временная метка начала взвешивания.
            public long StartTime { get; set; }

            // Временная метка первого падения ниже порога окончания.
            public long BelowThresholdSince { get; set; }

            // Временная метка последнего полученного измерения.
            public long LastTimestamp { get; set; }
        }
    }


}
